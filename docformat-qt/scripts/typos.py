TYPOS = {}      # 错形 → 正形
GUARDS = {}     # 错形 → (前面不能是的字, 后面不能是的字)；没护栏就不在表里
for _e in _IDIOMS + _WORDS + _PHRASES:
    TYPOS[_e[0]] = _e[1]
    if len(_e) > 2 and (_e[2] or _e[3]):
        GUARDS[_e[0]] = (_e[2], _e[3])

# 自我保护：错形若与正形相同、或本身就是某个正形的子串，改完再查还会报，
# 成死循环。这种条目直接剔除——正常情况下这里应该一条都剔不出来，
# 剔出来了说明我收词收错了，自测会把数量报出来。
DROPPED = sorted(w for w, r in TYPOS.items()
                 if w == r or any(w in v for v in TYPOS.values()))
for _w in DROPPED:
    TYPOS.pop(_w, None)
    GUARDS.pop(_w, None)


def pattern_of(wrong):
    """把一条错词编成带护栏的正则片段。

    护栏就是两个否定环视：前面不能是那几个字、后面不能是那几个字。
    「防犯」本身是错的（正形防范），但"预防犯罪"会跨词拼出这两个字——
    加上「前不能是预、后不能是罪」，真错的照抓，撞车的放过。
    """
    import re as _re
    before, after = GUARDS.get(wrong, ('', ''))
    pat = ''
    if before:
        pat += '(?<![{}])'.format(_re.escape(before))
    pat += _re.escape(wrong)
    if after:
        pat += '(?![{}])'.format(_re.escape(after))
    return pat


